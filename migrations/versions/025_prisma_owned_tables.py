"""Create the tables that only the Prisma schemas know about.

The single PostgreSQL database is shared by the FastAPI backend (SQLAlchemy +
Alembic) and the two Next.js apps (Prisma). Eleven tables have no SQLAlchemy
model and were created, on the previous server, by ``prisma db push`` or by
hand-run SQL files:

* web (apps/web/prisma/schema.prisma) — Better Auth ``users``, ``sessions``,
  ``accounts``, ``verification``, ``jwks``; ``font_cache``; ``user_signatures``;
* admin (apps/admin/prisma/schema.prisma) — Better Auth ``admin_users``,
  ``admin_accounts``, ``admin_sessions``, ``admin_verification``.

The move to the new host only replayed the Alembic chain, so the production
database had none of ``user_signatures``, ``font_cache`` and ``admin_*``
(saved signatures and account erasure failed with ``relation
"user_signatures" does not exist``; nobody could sign in to the admin app),
and a fresh database had none of the eleven. From this revision on, Alembic is
the ONLY thing that creates them: ``alembic upgrade head`` yields a complete
schema, and no ``prisma db push`` (which would also realign — or drop — every
SQLAlchemy table of the shared database) is ever needed.

DDL: generated by Prisma itself, not written by hand —
``prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script``
on both schemas (Prisma 7.10.1), keeping only the statements of the tables
above. Both schemas produce identical DDL for the ``admin_*`` tables; ``users``
comes from the web schema (the admin copy omits ``is_admin`` and ``role``).
tests/integration/test_migration_025_prisma_owned_tables.py re-runs that diff
against a migrated database and fails on any difference, so a change in a
Prisma model without a new migration is caught.

Idempotent, and a no-op on existing tables: every table is created only when
missing; an index or a foreign key is created only when no equivalent one
(same columns, same uniqueness / same referenced table) exists, whatever its
name — legacy setups named some of them differently (``admin_accounts_userId_idx``).
Existing tables keep their column types even where they differ from Prisma's
(production's Better Auth tables use ``varchar(255)`` and ``timestamptz``,
which Prisma reads identically): converting them would rewrite live auth
tables for no functional gain.

Downgrade is a documented no-op. ``users``, ``sessions``, ``accounts`` and
the ``admin_*`` tables hold every login of the product, and this revision
cannot tell a table it created from one that existed before it (production's
``users`` predates Alembic's knowledge of it). Dropping them on a downgrade
would destroy the authentication data of the running apps, while keeping them
costs nothing: revision 024 does not conflict with any of them.

Revision ID: 025_prisma_owned_tables
Revises: 024_document_quota_attribution
Create Date: 2026-10-28
"""

