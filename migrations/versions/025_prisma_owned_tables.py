@dataclass(frozen=True)
class _Index:
    name: str
    table: str
    columns: tuple[str, ...]
    unique: bool = False

    def sql(self) -> str:
        columns = ", ".join(f'"{column}"' for column in self.columns)
        kind = "UNIQUE INDEX" if self.unique else "INDEX"
        return f'CREATE {kind} IF NOT EXISTS "{self.name}" ON "{self.table}"({columns})'


@dataclass(frozen=True)
class _ForeignKey:
    name: str
    table: str
    column: str
    referred_table: str

    def sql(self) -> str:
        return (
            f'ALTER TABLE "{self.table}" ADD CONSTRAINT "{self.name}" '
            f'FOREIGN KEY ("{self.column}") REFERENCES "{self.referred_table}"("id") '
            "ON DELETE CASCADE ON UPDATE CASCADE"
        )


