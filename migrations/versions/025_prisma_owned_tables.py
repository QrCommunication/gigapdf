def _has_equivalent_index(inspector, index: _Index) -> bool:
    """An index (or unique constraint) on the same columns, at least as strict."""
    wanted = list(index.columns)
    for existing in inspector.get_indexes(index.table):
        if existing["column_names"] == wanted and (existing["unique"] or not index.unique):
            return True
    return any(
        constraint["column_names"] == wanted
        for constraint in inspector.get_unique_constraints(index.table)
    )


def _has_equivalent_foreign_key(inspector, foreign_key: _ForeignKey) -> bool:
    return any(
        existing["constrained_columns"] == [foreign_key.column]
        and existing["referred_table"] == foreign_key.referred_table
        for existing in inspector.get_foreign_keys(foreign_key.table)
    )


def upgrade() -> None:
    """Create whatever is missing; leave existing tables exactly as they are."""
    for _, ddl in _TABLES:
        op.execute(ddl)

    # Inspected after the CREATE TABLEs: the inspector caches per table.
    inspector = sa.inspect(op.get_bind())
    for index in _INDEXES:
        if not _has_equivalent_index(inspector, index):
            op.execute(index.sql())
    for foreign_key in _FOREIGN_KEYS:
        if not _has_equivalent_foreign_key(inspector, foreign_key):
            op.execute(foreign_key.sql())


